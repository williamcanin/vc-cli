#!/bin/bash
#
# setup-veracrypt-unmount.sh
#
# Configures automatic unmounting of all VeraCrypt volumes:
#   1. Before shutdown/reboot (via systemd service)
#   2. When logging out of Hyprland (via script + restricted sudoers rule)
#
# Usage: sudo ./setup-veracrypt-unmount.sh
#

set -euo pipefail

# --- 0. Initial checks ------------------------------------------------------

if [[ $EUID -ne 0 ]]; then
    echo "Error: run this script with sudo." >&2
    echo "  sudo ./setup-veracrypt-unmount.sh" >&2
    exit 1
fi

if ! command -v veracrypt &> /dev/null; then
    echo "Error: the 'veracrypt' binary was not found in PATH." >&2
    exit 1
fi

# Detect the "real" user (the user who invoked sudo), not root
TARGET_USER="${SUDO_USER:-}"
if [[ -z "$TARGET_USER" ]]; then
    read -rp "Could not detect the user via sudo. Enter your Linux username: " TARGET_USER
fi

if ! id "$TARGET_USER" &> /dev/null; then
    echo "Error: user '$TARGET_USER' does not exist." >&2
    exit 1
fi

TARGET_HOME=$(getent passwd "$TARGET_USER" | cut -d: -f6)
VERACRYPT_BIN=$(command -v veracrypt)

echo "==> Target user: $TARGET_USER (home: $TARGET_HOME)"
echo "==> VeraCrypt binary: $VERACRYPT_BIN"
echo

# --- 1. Unmount script ------------------------------------------------------

echo "==> Creating /usr/local/bin/veracrypt-unmount-all.sh"
cat > /usr/local/bin/veracrypt-unmount-all.sh << EOF
#!/bin/bash
# Unmounts all mounted VeraCrypt volumes. Generated by setup-veracrypt-unmount.sh
$VERACRYPT_BIN --text --dismount
EOF
chmod 755 /usr/local/bin/veracrypt-unmount-all.sh
echo "    OK"
echo

# --- 2. systemd service (shutdown/reboot) -----------------------------------

echo "==> Creating /etc/systemd/system/veracrypt-unmount.service"
cat > /etc/systemd/system/veracrypt-unmount.service << 'EOF'
[Unit]
Description=Unmount VeraCrypt volumes before shutdown/reboot
DefaultDependencies=no
Before=shutdown.target reboot.target halt.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/bin/true
ExecStop=/usr/local/bin/veracrypt-unmount-all.sh

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable veracrypt-unmount.service
echo "    OK (service enabled)"
echo

# --- 3. Restricted sudoers rule (logout without sudo password) --------------

SUDOERS_FILE="/etc/sudoers.d/veracrypt-unmount"
echo "==> Creating $SUDOERS_FILE"
echo "$TARGET_USER ALL=(root) NOPASSWD: /usr/local/bin/veracrypt-unmount-all.sh" > "$SUDOERS_FILE"
chmod 440 "$SUDOERS_FILE"

# Validate the syntax before trusting the file — prevents breaking system sudo
if ! visudo -c -f "$SUDOERS_FILE" &> /dev/null; then
    echo "Error: invalid syntax generated in $SUDOERS_FILE. Removing for safety." >&2
    rm -f "$SUDOERS_FILE"
    exit 1
fi
echo "    OK (syntax validated)"
echo

# --- 4. Hyprland logout script ----------------------------------------------

LOCAL_BIN="$TARGET_HOME/.local/bin"
LOGOUT_SCRIPT="$LOCAL_BIN/hypr-logout.sh"

echo "==> Creating $LOGOUT_SCRIPT"
mkdir -p "$LOCAL_BIN"
cat > "$LOGOUT_SCRIPT" << 'EOF'
#!/bin/bash
# Unmounts VeraCrypt volumes and exits the Hyprland session.
sudo /usr/local/bin/veracrypt-unmount-all.sh
hyprctl dispatch exit
EOF
chmod 755 "$LOGOUT_SCRIPT"
chown "$TARGET_USER:$TARGET_USER" "$LOGOUT_SCRIPT"
chown "$TARGET_USER:$TARGET_USER" "$LOCAL_BIN" 2>/dev/null || true
echo "    OK"
echo

# --- Summary ---------------------------------------------------------------

cat << EOF
==========================================================================
Everything is configured!

1. Shutdown/reboot: automatic, via veracrypt-unmount.service (already enabled).
   Test with: sudo systemctl stop veracrypt-unmount.service

2. Hyprland logout: one manual step remains.
   Open your hyprland.conf and replace your current logout bind with:

       bind = \$mainMod SHIFT, Q, exec, $LOGOUT_SCRIPT

   (adjust the key combination to match the one you currently use)

3. If you use a power menu (wlogout, etc.), point its logout action to:
   $LOGOUT_SCRIPT

To manually test unmounting at any time:
   sudo /usr/local/bin/veracrypt-unmount-all.sh
==========================================================================
EOF
